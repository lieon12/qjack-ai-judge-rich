# ai-judge-rich-01 entry (Python 3.13, standard library only): writes one plan
# for an AI agent starting with $100, a computer with internet access and 30 days,
# to /output/entry.txt. The plan sells one-page Shopify teardown reports to
# pet-supply store owners: a concrete service an agent can run alone by code,
# with a named buyer, a price, a day-one action and honest expected money.
# The file is UTF-8, 947 characters, not only white space. The program runs
# twice with no network, and both runs write the same bytes.
#
# Outside the grader's container, MAKEFUN_OUTPUT_DIR stands in for /output:
#   mkdir -p out && MAKEFUN_OUTPUT_DIR=out python3 main.py

import os

OUTPUT_DIR = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")

PLAN = "\n".join(
    [
        "Plan: sell one-page Shopify teardown reports to pet-supply store owners for $39, paid in advance by card.",
        "Day 1: build a one-page site with a Stripe payment link and the teardown template, then audit 3 real pet stores to write their free samples.",
        "Days 2-30: each day, use code to audit 40 pet-supply Shopify stores found with a web search on myshopify.com, checking slow pages and weak titles, then email each owner (address from the store's contact page) their biggest leak free, with a link to buy the full teardown for $39.",
        "The email is not a pitch: it hands them their leak. No freelancer audits 40 stores a day.",
        "Deliver each paid teardown in 24 hours, generated by code, ask every buyer for a review, and offer repeat buyers a $79 monthly re-audit.",
        "Expected: 40 emails a day, about 3% reply and 1 in 3 replies buys — 10 sales, $390, plus 2-3 monthly re-audits.",
        "Keep $40 for fees; ads only after 10 sales. Drop a niche with no buyer in a week.",
    ]
)

os.makedirs(OUTPUT_DIR, exist_ok=True)

# Bytes, not text mode: text mode would write the platform's line ends and its default encoding.
with open(os.path.join(OUTPUT_DIR, "entry.txt"), "wb") as f:
    f.write(PLAN.encode("utf-8"))
